import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { existsSync } from 'node:fs';
import { copyFile, mkdir, writeFile } from 'node:fs/promises';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// The build writes the installable plugin into OBSIDIAN_PLUGIN_DIR, normally <vault>/.obsidian/plugins/<plugin id>,
// so Obsidian loads it there and its data.json lives with the vault. Set it in the shell or in a gitignored .env.local
// (the shell wins); without it the build falls back to dist/. The build never writes data.json.
// Why: ai-hub/docs/adr/0003-build-into-the-vault.md
if (existsSync('.env.local')) process.loadEnvFile('.env.local');
const outdir = process.env.OBSIDIAN_PLUGIN_DIR || 'dist';

/** Copies manifest.json and styles.css next to main.js after every build, so the output folder is always complete. */
const completeDist = {
	name: 'complete-dist',
	setup(build) {
		build.onEnd(async (result) => {
			if (result.errors.length > 0) return;
			await mkdir(outdir, { recursive: true });
			await Promise.all([copyFile('manifest.json', `${outdir}/manifest.json`), copyFile('styles.css', `${outdir}/styles.css`)]);
			// Hot Reload only watches plugin folders that contain .git or .hotreload.
			if (!prod) await writeFile(`${outdir}/.hotreload`, '');
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
		...builtinModules.map((name) => `node:${name}`),
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: `${outdir}/main.js`,
	minify: prod,
	plugins: [completeDist],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
